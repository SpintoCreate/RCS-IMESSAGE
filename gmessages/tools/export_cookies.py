"""Encrypt only the libgm cookies and send the ciphertext over local USB.

This program never reads a browser database, writes a cookie file, or uploads
anything. Chrome/Edge DevTools provides the request Cookie header directly.
"""

import base64
import getpass
import hashlib
import json
import os
import secrets
import shutil
import subprocess
import sys
import threading
import time
from pathlib import Path

from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from mnemonic import Mnemonic
import pyperclip

REQUIRED = ("SID", "HSID", "SSID", "OSID", "APISID", "SAPISID")
OPTIONAL = ("__Secure-1PSIDTS",)
ALLOWED = set(REQUIRED + OPTIONAL)
PREFIX = "UMGM2:"
AAD = b"UnifiedMessages-GMessages-UMGM2"
PBKDF2_ITERATIONS = 600_000
MAX_PAYLOAD_CHARACTERS = 100_000
ACTIVITY = "com.unifiedmessages.app/com.unifiedmessages.gmessages.GMessagesDebugActivity"


def select_cookies(header: str) -> dict[str, str]:
    found: dict[str, str] = {}
    for field in header.split(";"):
        if "=" not in field:
            continue
        name, value = field.strip().split("=", 1)
        if name in ALLOWED:
            if not value or name in found:
                raise ValueError("A required cookie is empty or duplicated")
            found[name] = value
    missing = [name for name in REQUIRED if name not in found]
    if missing:
        raise ValueError("Missing cookies: " + ", ".join(missing))
    return found


def encrypt_payload(cookies: dict[str, str], passphrase: str, now_ms: int) -> str:
    """PBKDF2-HMAC-SHA256 plus AES-256-GCM using vetted standard libraries."""
    if len(passphrase.split("-")) != 9:
        raise ValueError("Expected the nine-word phrase generated by this helper")
    clean = {name: cookies[name] for name in REQUIRED if name in cookies}
    for name in OPTIONAL:
        if name in cookies:
            clean[name] = cookies[name]
    clean["__createdAtMs"] = now_ms
    salt = secrets.token_bytes(16)
    nonce = secrets.token_bytes(12)
    key = bytearray(hashlib.pbkdf2_hmac(
        "sha256", passphrase.encode("ascii"), salt, PBKDF2_ITERATIONS, dklen=32,
    ))
    try:
        cipher = AESGCM(bytes(key))
        encrypted = cipher.encrypt(
            nonce, json.dumps(clean, separators=(",", ":")).encode("utf-8"), AAD,
        )
        return PREFIX + base64.urlsafe_b64encode(salt + nonce + encrypted).decode("ascii").rstrip("=")
    finally:
        key[:] = b"\x00" * len(key)


def generate_passphrase() -> str:
    words = Mnemonic("english").wordlist
    if len(words) != 2048:
        raise RuntimeError("The expected 2048-word list is unavailable")
    return "-".join(secrets.choice(words) for _ in range(9))  # 99 bits of entropy.


def find_adb() -> str | None:
    if found := shutil.which("adb"):
        return found
    if os.name == "nt":
        candidate = Path(os.environ.get("LOCALAPPDATA", "")) / "Android" / "Sdk" / "platform-tools" / "adb.exe"
        if candidate.is_file():
            return str(candidate)
    for variable in ("ANDROID_HOME", "ANDROID_SDK_ROOT"):
        if root := os.environ.get(variable):
            candidate = Path(root) / "platform-tools" / ("adb.exe" if os.name == "nt" else "adb")
            if candidate.is_file():
                return str(candidate)
    return None


def send_over_usb(payload: str, adb: str | None = None) -> bool:
    """ADB carries only ciphertext to the installed app, without a cloud relay."""
    if len(payload) > 25_000:  # Windows command-line limit leaves room for ADB arguments.
        return False
    tool = adb or find_adb()
    if not tool:
        return False
    try:
        devices = subprocess.run([tool, "devices", "-l"], capture_output=True, text=True, timeout=10, check=True)
        authorized = [
            parts[0] for line in devices.stdout.splitlines()[1:]
            if (parts := line.split()) and len(parts) >= 3
            and parts[1] == "device" and any(item.startswith("usb:") for item in parts[2:])
        ]
        if len(authorized) != 1:
            return False
        result = subprocess.run(
            [tool, "shell", "am", "start", "-n", ACTIVITY, "--es", "encrypted_transfer", payload],
            capture_output=True, text=True, timeout=20, check=False,
        )
        return result.returncode == 0 and "Error:" not in result.stdout and "Error:" not in result.stderr
    except (OSError, subprocess.SubprocessError):
        return False


def main() -> int:
    print("Turn OFF Windows Settings > System > Clipboard > Clipboard history and Sync across devices before copying cookies.")
    if getpass.getpass("After checking that setting, type OFF (hidden): ").strip() != "OFF":
        print("Stopped before handling cookies.", file=sys.stderr)
        return 2
    print("Use the SAME Google Account selected in Google Messages > Device pairing.")
    print("Chrome InPrivate/Incognito > messages.google.com/web/config > F12 > Network.")
    print("Copy only /web/config's Cookie request-header value.")
    print("Wait for the hidden Cookie header prompt below; never paste at PS>.")
    header = getpass.getpass("Cookie header: ")
    try:
        cookies = select_cookies(header)
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        return 2
    header = ""
    try:
        pyperclip.copy("")  # Replace the raw browser Cookie header immediately.
    except pyperclip.PyperclipException:
        cookies.clear()
        print("Could not clear the PC clipboard. Clear it manually before retrying.", file=sys.stderr)
        return 2
    passphrase = generate_passphrase()
    payload = encrypt_payload(cookies, passphrase, int(time.time() * 1000))
    cookies.clear()
    if len(payload) > MAX_PAYLOAD_CHARACTERS:
        print("Browser session is too large for this transfer.", file=sys.stderr)
        return 2
    print("Your nine-word import passphrase (type it on the phone):", passphrase)
    print(f"Encrypted transfer size: {len(payload)} characters.")
    print("The encrypted transfer expires after 5 minutes.")
    if send_over_usb(payload):
        print("Encrypted transfer sent over USB into GMessagesDebug's paste box.")
    else:
        print("USB auto-fill failed. Windows clipboard history and cloud sync must remain OFF for local fallback.")
        try:
            pyperclip.copy(payload)
        except pyperclip.PyperclipException:
            print("USB transfer and local clipboard copy both failed. Check USB debugging.", file=sys.stderr)
            return 2
        print("ADB could not reach exactly one authorized USB phone. Encrypted text is on the PC clipboard.")
        print("Paste it into GMessagesDebug through Android Studio's local USB device mirror if available.")
        print("Do not use email, cloud clipboard sync, or a messaging app to move it.")
    print("After import, close DevTools and the private browser window.")
    finished = threading.Event()
    def wait_for_enter() -> None:
        try:
            input("Press Enter after import to clear this window, or wait 5 minutes.\n")
        except EOFError:
            pass
        finally:
            finished.set()
    threading.Thread(target=wait_for_enter, daemon=True).start()
    finished.wait(300)
    try:
        pyperclip.copy("")
    except pyperclip.PyperclipException:
        pass
    os.system("cls" if os.name == "nt" else "clear")
    print("Local clipboard and helper output cleared.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
